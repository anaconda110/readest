import rawDataset from '@/data/aiNovelReaderV2/lingjing-xingzhe-chapters.json';
import type { TOCItem } from '@/libs/document';
import { getAnalysisReportId } from '@/services/ai/analysisService';
import { aiStore } from '@/services/ai/storage/aiStore';
import type { AIAnalysisReport } from '@/services/ai/types';

interface AiNovelReaderV2DatasetReport {
  sectionIndex: number;
  chapterTitle: string;
  content: string;
  createdAt: number;
  updatedAt: number;
  sourceChapterIds: string[];
  sourceSummaryIds: string[];
}

interface AiNovelReaderV2Dataset {
  version: number;
  source: 'ai-novel-reader-v2';
  bookHash: string;
  bookTitle: string;
  authorName: string;
  sectionCount: number;
  tocSignature: Record<string, string>;
  reports: AiNovelReaderV2DatasetReport[];
}

export interface AiNovelReaderV2ImportContext {
  bookHash: string;
  bookTitle: string;
  authorName: string;
  toc: TOCItem[];
}

interface AnalysisReportImportStore {
  saveAnalysisReportsIfAbsent(reports: AIAnalysisReport[]): Promise<AIAnalysisReport[]>;
}

const dataset = rawDataset as AiNovelReaderV2Dataset;
const IMPORT_MODEL = 'ai-novel-reader-v2 / chapter-summary';
const IMPORT_COVERAGE =
  'Imported from an ai-novel-reader-v2 historical export generated from complete chapter text.';

export function flattenTocForImport(items: TOCItem[] = []): TOCItem[] {
  const flat: TOCItem[] = [];
  const visit = (entries: TOCItem[]) => {
    for (const item of entries) {
      flat.push(item);
      if (item.subitems?.length) visit(item.subitems);
    }
  };
  visit(items);
  return flat;
}

function matchesTarget(context: AiNovelReaderV2ImportContext): boolean {
  if (
    context.bookHash !== dataset.bookHash ||
    context.bookTitle.trim() !== dataset.bookTitle ||
    context.authorName.trim() !== dataset.authorName
  ) {
    return false;
  }

  const flatToc = flattenTocForImport(context.toc);
  if (flatToc.length !== dataset.sectionCount) return false;

  return Object.entries(dataset.tocSignature).every(([id, label], index) => {
    const item = flatToc[index];
    return item?.id === Number(id) && item.label === label;
  });
}

function toAnalysisReport(report: AiNovelReaderV2DatasetReport): AIAnalysisReport {
  return {
    id: getAnalysisReportId(dataset.bookHash, 'chapter', report.sectionIndex),
    bookHash: dataset.bookHash,
    bookTitle: dataset.bookTitle,
    kind: 'chapter',
    sectionIndex: report.sectionIndex,
    chapterTitle: report.chapterTitle,
    content: report.content,
    model: IMPORT_MODEL,
    status: 'complete',
    sources: [],
    coverage: IMPORT_COVERAGE,
    createdAt: report.createdAt,
    updatedAt: report.updatedAt,
    importedFrom: 'ai-novel-reader-v2',
    sourceChapterIds: report.sourceChapterIds,
    sourceSummaryIds: report.sourceSummaryIds,
  };
}

/**
 * Imports the bundled historical summaries once for the matching edition.
 * Existing reports win, so this never replaces analysis generated by the user.
 */
export async function importAiNovelReaderV2Reports(
  context: AiNovelReaderV2ImportContext,
  store: AnalysisReportImportStore = aiStore,
): Promise<number> {
  if (!matchesTarget(context)) return 0;
  const inserted = await store.saveAnalysisReportsIfAbsent(dataset.reports.map(toAnalysisReport));
  return inserted.length;
}
